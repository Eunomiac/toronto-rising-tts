/** Verify current sheet-backed APIs and Catalog? visibility; mock only the absent TTS connection. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || (fs.existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined),args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1920,height:1080}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.route('**/api/tts/execute-lua', route => route.fulfill({ json: { prints: [], returnValue: JSON.stringify({ok:true, seats:[]}) } }));
await page.goto(process.env.DASHBOARD_URL || 'http://127.0.0.1:8788');
await page.locator('#tab-scenes').click();
await page.locator('.lab-dock-rail').click();
await page.waitForSelector('.lab-mroster');
const data=await page.evaluate(async()=>{
 const get=async p=>{const r=await fetch(p);if(!r.ok)throw new Error(`${p}: ${r.status}`);return r.json()};
 return {catalogs:await get('/api/scene-catalogs'),exports:await get('/api/chronicle-exports'),generics:await get('/api/generic-npcs'),compulsions:await get('/api/compulsions')};
});
assert(data.exports.districts.length > 0 && data.exports.sites.length > 0); assert.equal(data.exports.weather.length,366);
assert(data.generics.npcs.length > 0); assert.equal(new Set(data.generics.npcs.map(n=>n.key)).size,data.generics.npcs.length);
assert(Object.keys(data.compulsions).length > 0); for (const row of Object.values(data.compulsions)) assert.deepEqual(row.variants.map(v => v.card).sort(), [1,2,3,4]);
const roster=page.locator('.lab-mroster');
const hidden=data.catalogs.namedNpcs.find(n=>n.catalog===false && !data.catalogs.namedNpcs.some(o=>o.catalog && o.fullName===n.fullName));
const shown=data.catalogs.namedNpcs.find(n=>n.catalog===true);
assert(hidden&&shown);
await roster.getByRole('button',{name:'Catalog',exact:true}).click();
await roster.getByRole('searchbox').fill(hidden.fullName);
await page.waitForTimeout(250);
assert.equal(await roster.locator(`[data-tr-dnd-roster="${hidden.characterKey}"]`).count(),0);
await roster.getByRole('searchbox').fill(shown.fullName);
await page.waitForTimeout(250);
assert.equal(await roster.locator(`[data-tr-dnd-roster="${shown.characterKey}"]`).count(),1);
await roster.getByRole('button',{name:'Generic',exact:true}).click();
await roster.getByRole('searchbox').fill('');
await page.waitForTimeout(300);
assert.equal(await roster.getByRole('searchbox').getAttribute('placeholder'),'Search generic NPCs…');
await roster.getByRole('button',{name:'Memoriam',exact:true}).click();
await roster.getByRole('searchbox').fill(hidden.fullName);
await page.waitForTimeout(300);
assert.equal(await roster.getByRole('searchbox').getAttribute('placeholder'),'Search Memoriam NPCs…');
assert.deepEqual(errors,[]);
console.log('PASS actual export APIs: locations, 366 weather days, distinct generic figures and four numbered variants per Compulsion.');
console.log(`PASS Catalog search excludes ${hidden.characterKey}; Catalog/Generic/Memoriam tabs exercised at 1920×1080; no browser exceptions.`);
await browser.close();
