"use strict";
// Import only runtime metadata; effect text and function columns are deliberately not executed.
const fs = require('node:fs');
const path = require('node:path');
const { parseCsv } = require('./lib/skyboxes_sheet_csv.js');
const { fetchTabCsv, writeAtomic } = require('./lib/google_sheet_fetch.js');
const SHEET = '11kcsl9vAqWeEBEFFmadMs65xpDqMNV8SkCaCNM_09bU';
const ROLL_COLUMNS = {Standard:'standard', Discipline:'discipline', Willpower:'willpowerRoll', Launch:'launch', Goal:'goal'};
function parseCards(rows) {
  const normalize = s => String(s || '').replace(/\s+/g, ' ').trim();
  const header = rows.findIndex(r => r.includes('Index') && r.includes('Name'));
  if (header < 0) throw new Error('Cards header missing');
  const columns = rows[header].map(normalize);
  const required = ['Index','Name','Category','Rarity','Value','DESIGN COMPLETE?',...Object.keys(ROLL_COLUMNS)];
  for (const name of required) if (!columns.includes(name)) throw new Error(`Missing Cards column: ${name}`);
  const read = (r,name) => r[columns.indexOf(name)];
  const cards = [], ids = new Set(), names = new Set();
  for (const r of rows.slice(header + 1)) {
    if (String(read(r,'Index') || '').trim()==='') continue;
    if (String(read(r,'DESIGN COMPLETE?') || '').trim() !== '✔️') continue;
    const index = Number(read(r,'Index')), name = String(read(r,'Name') || '').trim(), raw = String(read(r,'Value') || '').trim();
    if (!Number.isInteger(index) || index < 1 || !name || (raw !== 'X' && !/^-?\d+$/.test(raw))) throw new Error(`Invalid completed card: ${name}`);
    if (ids.has(index) || names.has(name)) throw new Error(`Duplicate completed card: ${name}`);
    ids.add(index); names.add(name);
    const rollTypes = {};
    for (const [column,type] of Object.entries(ROLL_COLUMNS)) {
      const flag=String(read(r,column)).toUpperCase();
      if (!['TRUE','FALSE'].includes(flag)) throw new Error(`Invalid ${column} checkbox for ${name}`);
      rollTypes[type]=flag==='TRUE';
    }
    cards.push({index, name, category: String(read(r,'Category') || '').trim(), rarity: String(read(r,'Rarity') || '').trim(), value: raw === 'X' ? 'X' : Number(raw), rollTypes});
  }
  if (!cards.length) throw new Error('No completed cards');
  return cards.sort((a,b) => a.index-b.index);
}
function render(cards) {
  const quote = s => JSON.stringify(s);
  return '-- Generated by npm run complications:import. Runtime metadata only; effects remain manual.\nreturn {\n' + cards.map(c => `  [${c.index}] = { name = ${quote(c.name)}, category = ${quote(c.category)}, rarity = ${quote(c.rarity)}, value = ${typeof c.value === 'number' ? c.value : quote(c.value)}, rollTypes = { ${Object.entries(c.rollTypes).map(([k,v])=>`${k} = ${v}`).join(', ')} } },`).join('\n') + '\n}\n';
}
async function main() {
  const input = process.argv.indexOf('--input');
  const rows = input >= 0 ? JSON.parse(fs.readFileSync(process.argv[input+1], 'utf8')) : parseCsv(await fetchTabCsv(SHEET, 'Cards', 'toronto-rising-complications/1.0'));
  const cards = parseCards(rows);
  writeAtomic(path.resolve(__dirname, '../../lib/complications_catalog.ttslua'), render(cards));
  console.log(`Imported ${cards.length} completed Complications definitions.`);
}
module.exports = {parseCards, render};
if (require.main === module) main().catch(e => { console.error(e.message); process.exitCode=1; });
