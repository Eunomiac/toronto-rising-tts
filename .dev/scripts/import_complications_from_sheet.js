"use strict";
// Import only runtime metadata; effect text and function columns are deliberately not executed.
const fs = require('node:fs');
const path = require('node:path');
const { parseCsv } = require('./lib/skyboxes_sheet_csv.js');
const { fetchTabCsv, writeAtomic } = require('./lib/google_sheet_fetch.js');
const SHEET = '11kcsl9vAqWeEBEFFmadMs65xpDqMNV8SkCaCNM_09bU';
function parseCards(rows) {
  const header = rows.findIndex(r => r[0] === 'Index' && r[1] === 'Name');
  if (header < 0) throw new Error('Cards header missing');
  const cards = [], ids = new Set(), names = new Set();
  for (const r of rows.slice(header + 1)) {
    if (String(r[8] || '').trim() !== '✔️') continue;
    const index = Number(r[0]), name = String(r[1] || '').trim(), raw = String(r[4] || '').trim();
    if (!Number.isInteger(index) || index < 1 || !name || (raw !== 'X' && !/^-?\d+$/.test(raw))) throw new Error(`Invalid completed card: ${r[1]}`);
    if (ids.has(index) || names.has(name)) throw new Error(`Duplicate completed card: ${name}`);
    ids.add(index); names.add(name);
    cards.push({index, name, category: String(r[2] || '').trim(), rarity: String(r[3] || '').trim(), value: raw === 'X' ? 'X' : Number(raw)});
  }
  if (!cards.length) throw new Error('No completed cards');
  return cards.sort((a,b) => a.index-b.index);
}
function render(cards) {
  const quote = s => JSON.stringify(s);
  return '-- Generated by npm run complications:import. Runtime metadata only; effects remain manual.\nreturn {\n' + cards.map(c => `  [${c.index}] = { name = ${quote(c.name)}, category = ${quote(c.category)}, rarity = ${quote(c.rarity)}, value = ${typeof c.value === 'number' ? c.value : quote(c.value)} },`).join('\n') + '\n}\n';
}
async function main() {
  const input = process.argv.indexOf('--input');
  const rows = input >= 0 ? JSON.parse(fs.readFileSync(process.argv[input+1], 'utf8')) : parseCsv(await fetchTabCsv(SHEET, 'Cards', 'toronto-rising-complications/1.0'));
  const cards = parseCards(rows);
  writeAtomic(path.resolve(__dirname, '../../lib/complications_catalog.ttslua'), render(cards));
  console.log(`Imported ${cards.length} completed Complications definitions.`);
}
module.exports = {parseCards, render};
if (require.main === module) main().catch(e => { console.error(e.message); process.exitCode=1; });
