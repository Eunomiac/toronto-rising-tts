"use strict";

// Build the shared Court from its own source on every XML/FULL build.
// The per-seat reference layer contains the other coteries, not the Court.
const fs = require("node:fs");
const path = require("node:path");
const { hydrateCoterieData } = require("./lib/coterie_hydrate.js");
const { buildTraitPlaceholderMap } = require("./lib/trait_sheet_xml.js");
const { loadPrincesCourtTemplates, replacePlaceholders, buildCourtProjectBlocks } = require("./princes_court_trait_placeholders.js");

function buildSharedCourt(root, coterieData) {
  const templates = loadPrincesCourtTemplates(root);
  const placeholders = buildTraitPlaceholderMap(hydrateCoterieData(coterieData), templates);
  const partial = fs.readFileSync(path.join(root, "ui/.templates/princes_court/partials/project_block.xml"), "utf8");
  placeholders.COURT_PROJECT_BLOCKS = buildCourtProjectBlocks(partial);
  const source = fs.readFileSync(path.join(root, "ui/.templates/princes_court/panel.xml"), "utf8");
  const xml = replacePlaceholders(source, placeholders)
    .replace(/_@@color@@/g, "")
    .replace(/[ \t]+$/gm, "");
  if (/@@[A-Za-z0-9_]+@@|##IF|##ENDIF/.test(xml)) {
    throw new Error("Court XML contains unexpanded template tokens");
  }
  return "<!-- Generated by .dev/scripts/extract_shared_princes_court.js. DO NOT EDIT. -->\n" + xml;
}

if (require.main === module) {
  const root = path.resolve(__dirname, "../..");
  const data = JSON.parse(fs.readFileSync(path.join(root, "lib/json/Coterie.json"), "utf8"));
  const output = path.join(root, "ui/shared/panel_ref_princes_court.xml");
  fs.writeFileSync(output, buildSharedCourt(root, data), "utf8");
  console.log("[extract_shared_princes_court] Rebuilt ui/shared/panel_ref_princes_court.xml");
}

module.exports = { buildSharedCourt };
