"use strict";

/**
 * Clip volumes for the scene-preview mixer, from `lib/soundscape_catalog.ttslua`.
 * Slider values are 0–100 (`Math.round(volume * 100)`), matching `soundView`.
 *
 * Writes `.dev/storyteller-dashboard/data/track-volumes.json`.
 * Run from the repo root: node .dev/scripts/generate_dashboard_track_volumes.js
 */

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..", "..");
const sourcePath = path.join(root, "lib", "soundscape_catalog.ttslua");
const outPath = path.join(root, ".dev", "storyteller-dashboard", "data", "track-volumes.json");

const src = fs.readFileSync(sourcePath, "utf8");
const start = src.indexOf("Catalog.TRACKS = {");
const end = src.indexOf("\nCatalog.SILENT_EFFECT");
if (start < 0 || end < start) {
  throw new Error("Catalog.TRACKS block was not found.");
}
const body = src.slice(start, end);
const entryRe = /\n  ([A-Za-z0-9_]+) = \{([\s\S]*?)\n  \},/g;
const tracks = [];
let match = entryRe.exec(body);
while (match) {
  const block = match[2];
  const key = (block.match(/\bkey = "([^"]+)"/) || [])[1] || match[1];
  const type = (block.match(/\btype = "([^"]+)"/) || [])[1];
  const subType = (block.match(/\bsubType = "([^"]+)"/) || [])[1];
  const volume = Number((block.match(/\bvolume = ([0-9.]+)/) || [])[1]);
  if (type && Number.isFinite(volume)) {
    tracks.push({ key, type, subType, volume });
  }
  match = entryRe.exec(body);
}
if (tracks.length === 0) {
  throw new Error("Catalog.TRACKS extract found no clips.");
}

const playlists = {};
const playlistClips = {};
for (const track of tracks) {
  if (track.type !== "backgroundMusic" || !track.subType) {
    continue;
  }
  const slider = Math.round(track.volume * 100);
  const previous = playlists[track.subType];
  if (previous === undefined) {
    playlists[track.subType] = slider;
  } else if (previous !== slider) {
    throw new Error(`Playlist ${track.subType} has more than one clip volume (${previous} and ${slider}).`);
  }
  if (!playlistClips[track.subType]) {
    playlistClips[track.subType] = [];
  }
  playlistClips[track.subType].push(track.key);
}
for (const key of Object.keys(playlistClips)) {
  playlistClips[key].sort();
}

const clips = {};
for (const track of tracks) {
  if (track.type === "location" || track.type === "weather" || track.type === "featureMusic") {
    clips[track.key] = Math.round(track.volume * 100);
  }
}

const payload = {
  generatedBy:
    "AUTO-GENERATED by .dev/scripts/generate_dashboard_track_volumes.js — DO NOT EDIT BY HAND. Regenerate: node .dev/scripts/generate_dashboard_track_volumes.js",
  playlists,
  playlistClips,
  clips,
};
fs.writeFileSync(outPath, `${JSON.stringify(payload, null, 2)}\n`);
console.log(`Wrote ${path.relative(root, outPath)} (${Object.keys(playlists).length} playlists, ${Object.keys(clips).length} clips).`);
