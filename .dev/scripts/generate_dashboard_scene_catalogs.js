/**
 * `C.WEATHER` as the dashboard decodes an hourly calendar code (same rules as `ChronicleWeather.parseCode`):
 * characters 1–2 pick `base` (rain layer, thunder), character 3 the temperature delta, character 5 the wind,
 * whose layer is `warm` above `warmThreshold` °C and `cold` at or below it.
 */
function parseWeatherCodes(source) {
  const weather = extractBlock(source, "C.WEATHER =");
  const warmThreshold = readNumberField(weather, "WARM_TEMPERATURE_THRESHOLD");
  if (warmThreshold === null) {
    throw new Error("C.WEATHER is missing WARM_TEMPERATURE_THRESHOLD.");
  }
  const base = {};
  for (const entry of parseTopLevelEntries(extractBlock(weather, "Base ="))) {
    const rain = readStringField(entry.body, "rainAudio");
    if (!rain) {
      throw new Error(`C.WEATHER.Base.${entry.key} is missing rainAudio.`);
    }
    base[entry.key] = { rain, thunder: readBooleanField(entry.body, "isThunder") === true };
  }
  const temperatureDelta = {};
  for (const m of extractBlock(weather, "TemperatureDelta =").matchAll(/(?:\["([^"]+)"\]|\b([A-Za-z]))\s*=\s*(-?\d+)/g)) {
    temperatureDelta[m[1] ?? m[2]] = Number(m[3]);
  }
  const wind = {};
  for (const entry of parseTopLevelEntries(extractBlock(weather, "Wind ="))) {
    const warm = readStringField(entry.body, "windAudioIfWarm");
    const cold = readStringField(entry.body, "windAudioIfCold");
    if (!warm || !cold) {
      throw new Error(`C.WEATHER.Wind.${entry.key} is missing windAudioIfWarm / windAudioIfCold.`);
    }
    wind[entry.key] = { warm, cold };
  }
  if (Object.keys(base).length === 0 || Object.keys(temperatureDelta).length === 0 || Object.keys(wind).length === 0) {
    throw new Error("C.WEATHER extract is missing Base, TemperatureDelta or Wind rows.");
  }
  return { warmThreshold, base, temperatureDelta, wind };
}

const BLOOD_POTENCY_FIELDS = ["bloodSurge", "mending", "discBonus", "discReroll", "baneSeverity"];

/** `BPC.BloodPotency` rows 0–10 (NPC stat rolls read surge, mending, discipline bonus and reroll from it). */
function parseBloodPotency(source) {
  const block = extractBlock(source, "BPC.BloodPotency =");
  const rows = [...block.matchAll(/\[(\d+)\]\s*=\s*(\{[^}]*\})/g)].map((m) => {
    const row = { level: Number(m[1]) };
    for (const field of BLOOD_POTENCY_FIELDS) {
      const value = readNumberField(m[2], field);
      if (value === null) {
        throw new Error(`BPC.BloodPotency[${m[1]}] is missing ${field}.`);
      }
      row[field] = value;
    }
    return row;
  });
  rows.sort((a, b) => a.level - b.level);
  if (rows.length !== 11 || rows.some((row, index) => row.level !== index)) {
    throw new Error("BPC.BloodPotency must have rows 0 to 10.");
  }
  return rows;
}

/** Roll type values (`C.RollType`) of a `[C.RollType.X] = true` set in lib/constants.ttslua. */
function parseRollTypeSet(constants, marker) {
  const names = {};
  for (const m of extractBlock(constants, "C.RollType =").matchAll(/([A-Z_]+)\s*=\s*"([^"]+)"/g)) {
    names[m[1]] = m[2];
  }
  const set = [...extractBlock(constants, marker).matchAll(/\[C\.RollType\.([A-Z_]+)\]\s*=\s*true/g)].map((m) => {
    if (!names[m[1]]) {
      throw new Error(`${marker} names an unknown roll type ${m[1]}.`);
    }
    return names[m[1]];
  });
  if (set.length === 0) {
    throw new Error(`${marker} is empty.`);
  }
  return set;
}

/** `CD.STRUCTURAL_NEGATING` in source order; each label is its negating condition's name without the leading "No ". */
function parseStructuralRollOptions(conditionSrc) {
  const block = extractBlock(conditionSrc, "CD.STRUCTURAL_NEGATING =");
  const defs = parseTopLevelEntries(extractBlock(conditionSrc, "CD.Defs ="));
  const options = [...block.matchAll(/([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"([^"]+)"/g)].map((m) => {
    const def = defs.find((entry) => (readStringField(entry.body, "id") || entry.key) === m[2]);
    const displayName = def ? readStringField(def.body, "displayName") : null;
    if (!displayName || !displayName.startsWith("No ")) {
      throw new Error(`CD.STRUCTURAL_NEGATING.${m[1]}: condition ${m[2]} needs a displayName starting with "No ".`);
    }
    return { key: m[1], label: displayName.slice(3) };
  });
  if (options.length === 0) {
    throw new Error("CD.STRUCTURAL_NEGATING is empty.");
  }
  return options;
}

function main() {
  const constants = fs.readFileSync(constantsPath, "utf8");
  const skyboxesSrc = fs.readFileSync(skyboxesPath, "utf8");
  const soundscapeSrc = fs.readFileSync(soundscapePath, "utf8");
  const conditionSrc = fs.readFileSync(conditionDefsPath, "utf8");
  const npcsSrc = fs.readFileSync(npcsDataPath, "utf8");
  const boardSrc = fs.readFileSync(gameboardDataPath, "utf8");

  const playerColors = parsePlayerColors(constants);
  const npcSeats = parseNpcSeats(constants);

  const cfg = readRepoAssetsConfig();
  const save = resolveChronicleSaveFile(cfg.defaultSaveName, cfg.savesDir);
  const saveText = fs.readFileSync(save.savePath, "utf8");
  const cardUrls = readCardAssetUrls(saveText);

  const locationsSrc = fs.readFileSync(locationsPath, "utf8");
  const districts = parseTopLevelEntries(extractBlock(locationsSrc, "local Districts =")).map((entry) => ({
    key: entry.key,
    name: readStringField(entry.body, "name") || entry.key,
    conditions: readStringListField(entry.body, "conditions"),
    cardUrl: cardUrls.get(`districtCard_${entry.key}`) ?? null,
  }));
  districts.sort((a, b) => a.name.localeCompare(b.name));

  const sites = parseTopLevelEntries(extractBlock(locationsSrc, "LocationsCatalog.Sites =")).map((entry) => {
    const districtMatch = entry.body.match(/district\s*=\s*Districts\.([A-Za-z_][A-Za-z0-9_]*)/);
    const soundTrackMatch = entry.body.match(/track\s*=\s*"([^"]+)"/);
    return {
      key: entry.key,
      name: readStringField(entry.body, "name") || entry.key,
      districtKey: districtMatch ? districtMatch[1] : null,
      isTopFogActive: readBooleanField(entry.body, "isTopFogActive"),
      isIndoors: readBooleanField(entry.body, "isIndoors"),
      skybox: readStringField(entry.body, "skybox"),
      locationTrack: soundTrackMatch ? soundTrackMatch[1] : null,
      conditions: readStringListField(entry.body, "conditions"),
      cardUrl: siteCardUrl(cardUrls, entry.key),
    };
  });
  sites.sort((a, b) => a.name.localeCompare(b.name));

  const tables = parseTopLevelEntries(extractBlock(constants, "C.Tables =")).map((entry) => {
    const slotCapacity = readNumberField(entry.body, "slotCapacity");
    if (slotCapacity === null) {
      throw new Error(`C.Tables[${JSON.stringify(entry.key)}] is missing slotCapacity.`);
    }
    return { key: entry.key, slotCapacity, randomSeating: readBooleanField(entry.body, "isRandomSeating") === true };
  });

  const lightModes = parseTopLevelEntries(extractBlock(constants, "C.LightModes =")).map((entry) => entry.key);

  const skyboxes = parseTopLevelEntries(extractBlock(skyboxesSrc, "SkyboxesCatalog.Skyboxes ="))
    .filter((entry) => readBooleanField(entry.body, "isShown") !== false)
    .map((entry) => ({
      key: entry.key,
      display: readStringField(entry.body, "display") || entry.key,
    }));

  const memoriamPeriods = parseTopLevelEntries(extractBlock(skyboxesSrc, "SkyboxesCatalog.MemoriamSkyboxes ="))
    .map((entry) => {
      const startYear = readNumberField(entry.body, "startYear");
      const endYear = readNumberField(entry.body, "endYear");
      const location = readStringField(entry.body, "location");
      if (startYear === null || endYear === null || !location) {
        throw new Error(`SkyboxesCatalog.MemoriamSkyboxes.${entry.key} is missing startYear/endYear/location.`);
      }
      const panels = ["panelA", "panelB", "panelC", "panelD"].flatMap((panelKey) => {
        if (!entry.body.includes(`${panelKey} =`)) {
          return [];
        }
        const display = readStringField(extractBlock(entry.body, `${panelKey} =`), "display");
        if (!display) {
          throw new Error(`SkyboxesCatalog.MemoriamSkyboxes.${entry.key}.${panelKey} is missing display.`);
        }
        return [{ key: panelKey, display }];
      });
      return { key: entry.key, characters: readStringListField(entry.body, "characters"), startYear, endYear, location, panels };
    })
    .sort((a, b) => a.startYear - b.startYear || a.endYear - b.endYear);

  const trackKeysOfType = (type) =>
    parseTopLevelEntries(extractBlock(soundscapeSrc, "Catalog.TRACKS ="))
      .filter((entry) => readStringField(entry.body, "type") === type)
      .map((entry) => readStringField(entry.body, "key") || entry.key);
  const locationTracks = trackKeysOfType("location");
  const featuredTracks = trackKeysOfType("featureMusic");

  const weatherCodes = parseWeatherCodes(constants);
  const structuralRollOptions = parseStructuralRollOptions(conditionSrc);
  const bloodPotency = parseBloodPotency(fs.readFileSync(bloodPotencyPath, "utf8"));
  const rollTypeRules = {
    bloodSurge: parseRollTypeSet(constants, "C.RollTypesBloodSurge ="),
    withoutHunger: parseRollTypeSet(constants, "C.RollTypesWithoutHunger ="),
  };

  const playlistsBlock = extractBlock(soundscapeSrc, "Catalog.PLAYLISTS =");
  const bgBlock = extractBlock(playlistsBlock, "backgroundMusic =");
  const backgroundMoods = parseTopLevelEntries(bgBlock).map((entry) => entry.key);

  const conditions = parseTopLevelEntries(extractBlock(conditionSrc, "CD.Defs ="))
    .filter((entry) => readBooleanField(entry.body, "canApplyManually") === true)
    .map((entry) => ({
      id: readStringField(entry.body, "id") || entry.key,
      displayName: readStringField(entry.body, "displayName") || entry.key,
    }));

  const npcRoster = readNpcRoster();
  const characters = parseTopLevelEntries(extractBlock(npcsSrc, "D.characters =")).map((entry) => ({
    characterKey: entry.key,
    fullName: readStringField(entry.body, "fullName") || readStringField(entry.body, "name") || entry.key,
    isPC: readBooleanField(entry.body, "isPC") === true,
    pickerGroups: npcRoster.members[entry.key] ?? [],
  }));

  const pcs = characters.filter((c) => c.isPC);
  const namedNpcs = characters.filter((c) => !c.isPC);
  const unknownMembers = Object.keys(npcRoster.members).filter((key) => !namedNpcs.some((npc) => npc.characterKey === key));
  if (unknownMembers.length > 0) {
    throw new Error(`${npcRoster.where} members are not named NPCs in D.characters: ${unknownMembers.join(", ")}.`);
  }
  for (const [group, boss] of Object.entries(npcRoster.bosses)) {
    if (!(npcRoster.members[boss] ?? []).includes(group)) {
      throw new Error(`${npcRoster.where} boss of ${group} (${boss}) is not a member of ${group}.`);
    }
  }

  const chronicleBlock = extractBlock(constants, "C.CHRONICLE_DATA =");
  const coterieEntries = parseTopLevelEntries(extractBlock(chronicleBlock, "coteries ="));
  if (coterieEntries.length === 0) {
    throw new Error("C.CHRONICLE_DATA.coteries extract is empty.");
  }
  const pickerGroupLabels = { ...npcRoster.groupLabels };
  for (const entry of coterieEntries) {
    const name = readStringField(entry.body, "name");
    if (!name) {
      throw new Error(`C.CHRONICLE_DATA.coteries.${entry.key} is missing name.`);
    }
    pickerGroupLabels[entry.key] = name;
  }
  const missingGroupLabels = [];
  for (const npc of namedNpcs) {
    for (const group of npc.pickerGroups) {
      if (!pickerGroupLabels[group]) {
        missingGroupLabels.push(group);
      }
    }
  }
  const uniqueMissing = [...new Set(missingGroupLabels)].sort();
  if (uniqueMissing.length > 0) {
    throw new Error(
      `No display name for NPC roster group(s): ${uniqueMissing.join(", ")}. Add them to C.CHRONICLE_DATA.coteries or ${npcRoster.where} groupLabels.`,
    );
  }

  const stage = loadDashboardStageWorld(saveText, save);
  const snapCfg = parseControlBoardSnap(boardSrc);
  const polarSnaps = generatePolarSnaps(snapCfg, stage);

  const missingPcs = REQUIRED_PC_KEYS.filter((key) => !pcs.some((pc) => pc.characterKey === key));
  if (missingPcs.length > 0) {
    throw new Error(`D.characters is missing required PC key(s): ${missingPcs.join(", ")}`);
  }
  for (const color of REQUIRED_PLAYER_COLORS) {
    if (!playerColors.includes(color)) {
      throw new Error(`C.PlayerColors is missing ${color}.`);
    }
  }
  for (const seat of REQUIRED_NPC_SEATS) {
    if (!npcSeats.includes(seat)) {
      throw new Error(`C.NPCSeats is missing ${seat}.`);
    }
  }
  if (!tables.some((t) => t.key === "Table A")) {
    throw new Error('C.Tables is missing "Table A".');
  }
  if (districts.length === 0) {
    throw new Error("C.Districts extract is empty.");
  }
  if (sites.length === 0) {
    throw new Error("C.Sites extract is empty.");
  }
  if (lightModes.length === 0) {
    throw new Error("C.LightModes extract is empty.");
  }
  if (skyboxes.length === 0) {
    throw new Error("SkyboxesCatalog.Skyboxes extract is empty.");
  }
  if (locationTracks.length === 0) {
    throw new Error("Catalog.TRACKS location extract is empty.");
  }
  if (featuredTracks.length === 0) {
    throw new Error("Catalog.TRACKS featureMusic extract is empty.");
  }
  if (memoriamPeriods.length === 0) {
    throw new Error("SkyboxesCatalog.MemoriamSkyboxes extract is empty.");
  }
  if (conditions.length === 0) {
    throw new Error("CD.Defs extract found no canApplyManually conditions.");
  }
  if (namedNpcs.length === 0) {
    throw new Error("D.characters extract found no named NPCs.");
  }
  if (polarSnaps.length === 0) {
    throw new Error("CONTROL_BOARD polar snap generation produced zero snaps.");
  }

  const catalogs = {
    generatedBy: DO_NOT_EDIT,
    playerColors,
    npcSeats,
    pcs,
    namedNpcs,
    districts,
    sites,
    tables,
    lightModes,
    skyboxes,
    memoriamPeriods,
    locationTracks,
    featuredTracks,
    backgroundMoods,
    weatherCodes,
    conditions,
    structuralRollOptions,
    bloodPotency,
    rollTypeRules,
    pickerGroupLabels,
    groupBosses: npcRoster.bosses,
  };

  const snaps = {
    generatedBy: DO_NOT_EDIT,
    stageBoard: stage.stageBoard,
    polar: polarSnaps,
  };

  fs.mkdirSync(path.dirname(catalogsOutPath), { recursive: true });
  fs.writeFileSync(catalogsOutPath, `${JSON.stringify(catalogs, null, 2)}\n`);
  fs.writeFileSync(snapsOutPath, `${JSON.stringify(snaps, null, 2)}\n`);
  console.log(
    `Wrote ${path.relative(root, catalogsOutPath)} (${namedNpcs.length} named NPCs, ${pcs.length} PCs) and ${path.relative(root, snapsOutPath)} (${polarSnaps.length} polar snaps; stagger half-extents ${stage.stageBoard.halfWidthX} × ${stage.stageBoard.halfDepthZ}).`,
  );
}

main();
