#!/usr/bin/env node
"use strict";

// Builds the named-NPC figurine image catalog (front/back URLs) used by on-demand spawning
// (`core/npc_spawn.ttslua`, TOR-707). Cross-references `D.characters` in lib/npcs_data.ttslua
// against the save JSON:
//   1. npc_figurine objects with GM notes `npcInstance:<key>` (CustomImage URLs);
//   2. seated figurines via saved gameState `npcs.instances[key].figurineGuid`;
//   3. the previous catalog (.dev/custom-ui-assets/npc-figurine-hosted-urls.json);
//   4. CustomUIAssets `<key>` / `<key>Back` (new uploads; also a cross-check).
// `--refresh key1,key2` prefers CustomUIAssets over the previous catalog for re-uploaded art.
//
// Usage:
//   node .tools/custom-ui-assets/extract-npc-figurine-urls.js --saveName 230
//   node .tools/custom-ui-assets/extract-npc-figurine-urls.js --save path/to/TS_Save_230.json
//   node .tools/custom-ui-assets/extract-npc-figurine-urls.js --saveName 230 --refresh abbasFaruk

const fs = require("fs");
const path = require("path");
const { resolveSavePath } = require("../tts-save/resolve-save-path");
const {
  extractCharacterKeysFromNpcsData,
  readCustomUiAssetMap,
  deriveNpcGroupAssetNames,
  mergeNpcGroupRowsFromGeneratedFile,
  escapeForLuaString,
  ensureParentDir,
  GM_FIGURINE_PREFIX,
  NPC_FIGURINE_TAG,
} = require("./lib/npc-asset-helpers");

/**
 * @param {string[]} argv
 * @returns {Record<string, string>}
 */
function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (!token.startsWith("--")) {
      continue;
    }
    const key = token.slice(2);
    const next = argv[i + 1];
    if (next === undefined || next.startsWith("--")) {
      args[key] = "1";
    } else {
      args[key] = next;
      i += 1;
    }
  }
  return args;
}

/**
 * @param {unknown} node
 * @param {(obj: Record<string, unknown>) => void} visit
 */
function walkObjectStates(node, visit) {
  if (Array.isArray(node)) {
    for (const child of node) {
      walkObjectStates(child, visit);
    }
    return;
  }
  if (!node || typeof node !== "object") {
    return;
  }
  const obj = /** @type {Record<string, unknown>} */ (node);
  if (typeof obj.GUID === "string") {
    visit(obj);
  }
  for (const key of ["ObjectStates", "ContainedObjects"]) {
    if (Array.isArray(obj[key])) {
      walkObjectStates(obj[key], visit);
    }
  }
  if (obj.States && typeof obj.States === "object") {
    walkObjectStates(Object.values(obj.States), visit);
  }
}

/**
 * @param {Record<string, unknown>} obj
 * @returns {{ front: string; back: string } | null}
 */
function urlsFromFigurine(obj) {
  const img = obj.CustomImage;
  if (!img || typeof img !== "object") {
    return null;
  }
  const row = /** @type {Record<string, unknown>} */ (img);
  const front = typeof row.ImageURL === "string" ? row.ImageURL.trim() : "";
  const back = typeof row.ImageSecondaryURL === "string" ? row.ImageSecondaryURL.trim() : "";
  if (front === "" || back === "") {
    return null;
  }
  return { front, back };
}

/**
 * @param {Record<string, unknown>} saveRoot
 * @returns {Record<string, { figurineGuid?: string }>}
 */
function readSavedNpcInstances(saveRoot) {
  const raw = saveRoot.LuaScriptState;
  if (typeof raw !== "string" || raw.trim() === "") {
    return {};
  }
  const state = JSON.parse(raw);
  const instances = state && state.npcs && state.npcs.instances;
  return instances && typeof instances === "object" ? instances : {};
}

/**
 * @param {Record<string, { front: string; back: string }>} catalog
 * @returns {string}
 */
function buildLuaModule(catalog) {
  const keys = Object.keys(catalog).sort((a, b) => a.localeCompare(b, "en"));
  const lines = keys.map((characterKey) => {
    const row = catalog[characterKey];
    return [
      `  ${characterKey} = {`,
      `    front = "${escapeForLuaString(row.front)}",`,
      `    back = "${escapeForLuaString(row.back)}",`,
      "  },",
    ].join("\n");
  });
  return [
    "-- Auto-generated by .tools/custom-ui-assets/extract-npc-figurine-urls.js — do not edit by hand.",
    "-- Named NPC figurine images (Figurine_Custom ImageURL / ImageSecondaryURL) for on-demand spawn.",
    "local M = {",
    ...lines,
    "}",
    "",
    "return M",
    "",
  ].join("\n");
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const npcsDataPath = path.resolve(args.npcsData || "lib/npcs_data.ttslua");
  const savePath = args.save
    ? path.resolve(args.save)
    : resolveSavePath((args.saveName || "230").trim(), args.savesDir).savePath;
  const luaOut = path.resolve(args.luaOut || "lib/npc_figurine_hosted_urls.ttslua");
  const jsonOut = path.resolve(args.out || ".dev/custom-ui-assets/npc-figurine-hosted-urls.json");
  const generatedAssetsPath = path.resolve(
    args.generatedAssets || ".dev/custom-ui-assets/npc-group-generated-assets.json",
  );

  // Keys whose re-uploaded art should replace the stored catalog row (comma-separated).
  const refreshKeys = new Set(
    (args.refresh || "").split(",").map((k) => k.trim()).filter((k) => k !== ""),
  );

  console.log(`Save: ${savePath}`);
  const characterKeys = [...extractCharacterKeysFromNpcsData(fs.readFileSync(npcsDataPath, "utf8"))]
    .sort((a, b) => a.localeCompare(b, "en"));
  const saveRoot = JSON.parse(fs.readFileSync(savePath, "utf8"));

  // Existing catalog survives a save that no longer holds the figurines (after the pool is retired).
  /** @type {Record<string, { front: string; back: string }>} */
  let previous = {};
  if (fs.existsSync(jsonOut)) {
    const prior = JSON.parse(fs.readFileSync(jsonOut, "utf8"));
    if (prior && typeof prior.byCharacterKey === "object") {
      previous = prior.byCharacterKey;
    }
  }

  /** @type {Map<string, Record<string, unknown>>} */
  const figurineByKey = new Map();
  /** @type {Map<string, Record<string, unknown>>} */
  const objectByGuid = new Map();
  /** @type {string[]} */
  const unknownFigurineKeys = [];
  const keySet = new Set(characterKeys);
  walkObjectStates(saveRoot.ObjectStates, (obj) => {
    objectByGuid.set(/** @type {string} */ (obj.GUID), obj);
    const tags = Array.isArray(obj.Tags) ? obj.Tags : [];
    const notes = typeof obj.GMNotes === "string" ? obj.GMNotes : "";
    if (!tags.includes(NPC_FIGURINE_TAG) || !notes.startsWith(GM_FIGURINE_PREFIX)) {
      return;
    }
    const key = notes.slice(GM_FIGURINE_PREFIX.length);
    if (!keySet.has(key)) {
      unknownFigurineKeys.push(key);
      return;
    }
    if (!figurineByKey.has(key)) {
      figurineByKey.set(key, obj);
    }
  });

  const instances = readSavedNpcInstances(saveRoot);
  const assetMap = readCustomUiAssetMap(saveRoot);
  mergeNpcGroupRowsFromGeneratedFile(assetMap, generatedAssetsPath);

  /** @type {Record<string, { front: string; back: string }>} */
  const catalog = {};
  /** @type {Record<string, string>} */
  const sourceByKey = {};
  /** @type {string[]} */
  const missing = [];
  /** @type {{ key: string; side: string; object: string; customUiAsset: string }[]} */
  const mismatches = [];

  for (const key of characterKeys) {
    let urls = null;
    let source = "";
    const fig = figurineByKey.get(key);
    if (fig) {
      urls = urlsFromFigurine(fig);
      source = "figurine";
    }
    if (!urls) {
      const rec = instances[key];
      const guid = rec && typeof rec.figurineGuid === "string" ? rec.figurineGuid : "";
      const obj = guid ? objectByGuid.get(guid) : undefined;
      if (obj) {
        urls = urlsFromFigurine(obj);
        source = "instanceGuid";
      }
    }
    const names = deriveNpcGroupAssetNames(key);
    const assetFront = assetMap.get(names.figurineFront) || "";
    const assetBack = assetMap.get(names.figurineBack) || "";
    const hasAssets = assetFront !== "" && assetBack !== "";
    if (!urls && hasAssets && refreshKeys.has(key)) {
      urls = { front: assetFront, back: assetBack };
      source = "customUiAssets";
    }
    if (!urls && previous[key] && previous[key].front && previous[key].back) {
      urls = { front: previous[key].front, back: previous[key].back };
      source = "previousCatalog";
    }
    if (!urls && hasAssets) {
      urls = { front: assetFront, back: assetBack };
      source = "customUiAssets";
    }
    if (!urls) {
      missing.push(key);
      continue;
    }
    if (source === "figurine" || source === "instanceGuid") {
      if (assetFront !== "" && assetFront !== urls.front) {
        mismatches.push({ key, side: "front", object: urls.front, customUiAsset: assetFront });
      }
      if (assetBack !== "" && assetBack !== urls.back) {
        mismatches.push({ key, side: "back", object: urls.back, customUiAsset: assetBack });
      }
    }
    catalog[key] = urls;
    sourceByKey[key] = source;
  }

  const report = {
    generatedAt: new Date().toISOString(),
    source: "extract-npc-figurine-urls",
    save: savePath,
    characterCount: characterKeys.length,
    resolvedCount: Object.keys(catalog).length,
    missingCharacterKeys: missing,
    urlMismatches: mismatches,
    figurinesNotInCatalog: [...new Set(unknownFigurineKeys)].sort((a, b) => a.localeCompare(b, "en")),
    sourceByKey,
    byCharacterKey: catalog,
  };

  ensureParentDir(jsonOut);
  fs.writeFileSync(jsonOut, `${JSON.stringify(report, null, 2)}\n`, "utf8");
  ensureParentDir(luaOut);
  fs.writeFileSync(luaOut, buildLuaModule(catalog), "utf8");

  console.log(`Wrote ${luaOut}`);
  console.log(`Wrote ${jsonOut}`);
  console.log(`Resolved ${report.resolvedCount}/${report.characterCount} characters.`);
  if (mismatches.length > 0) {
    console.log(`URL mismatches (figurine object vs CustomUIAssets): ${mismatches.length} — figurine URL kept.`);
  }
  if (report.figurinesNotInCatalog.length > 0) {
    console.log(`Figurines in save with no npcs_data key: ${report.figurinesNotInCatalog.join(", ")}`);
  }
  if (missing.length > 0) {
    console.error(`Missing figurine URLs: ${missing.join(", ")}`);
    process.exitCode = 2;
  }
}

main();
